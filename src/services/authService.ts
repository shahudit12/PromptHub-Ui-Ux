export function getAppUrl(): string {
  if (typeof window !== 'undefined' && window.location?.origin) {
    return window.location.origin.replace(/\/$/, '');
  }
  return 'http://localhost:5173';
}

export function isValidPersistentUsername(username?: string | null): boolean {
  if (!username || typeof username !== 'string') return false;
  const clean = username.trim().toLowerCase();
  if (clean.length < 3 || clean.length > 30) return false;
  if (!/^[a-z0-9_]+$/.test(clean)) return false;
  if (clean.startsWith('user_tmp_')) return false;
  return true;
}

export function isAutoGeneratedOrRandomUsername(username?: string | null): boolean {
  if (!username || typeof username !== 'string') return true;
  const clean = username.trim().toLowerCase();
  if (!clean) return true;
  if (clean === 'user' || clean === 'developer' || clean === 'architect' || clean === 'anonymous') return true;
  if (clean.startsWith('user_tmp_')) return true;
  if (/^user_[0-9a-f]{6,}/i.test(clean)) return true;
  if (/^user_\d{6,}/i.test(clean)) return true;
  return false;
}

export function deriveUsernameFromName(name?: string | null, email?: string | null): string {
  const cleanName = (name || '').trim();
  if (cleanName) {
    const fromName = cleanName
      .toLowerCase()
      .replace(/[\s.\-]+/g, '_')
      .replace(/[^a-z0-9_]/g, '')
      .replace(/_+/g, '_')
      .replace(/^_+|_+$/g, '');

    if (fromName.length >= 3) {
      return fromName.slice(0, 30);
    }
  }
  const cleanEmail = (email || '').split('@')[0] || 'user';
  return cleanEmail.toLowerCase().replace(/[^a-z0-9_]/g, '').slice(0, 30) || 'demo_user';
}

