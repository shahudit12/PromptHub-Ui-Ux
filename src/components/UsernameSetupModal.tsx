import React, { useState, useEffect } from 'react';
import { createPortal } from 'react-dom';
import { motion, AnimatePresence } from 'framer-motion';
import { useApp } from '../context/AppContext';
import { User, Phone, CheckCircle, AlertCircle, ArrowRight, X, Camera, Loader2, ShieldCheck } from 'lucide-react';
import { ImageCropModal } from './ImageCropModal';
import { avatarUploadService } from '../services/avatarUploadService';
import { UserAvatar } from './UserAvatar';
import { isAutoGeneratedOrRandomUsername, deriveUsernameFromName } from '../services/authService';

export interface UsernameSetupModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const UsernameSetupModal: React.FC<UsernameSetupModalProps> = ({ isOpen, onClose }) => {
  const { user, updateUser, showToast } = useApp();

  const [usernameInput, setUsernameInput] = useState('');
  const [displayNameInput, setDisplayNameInput] = useState('');
  const [phoneInput, setPhoneInput] = useState('');
  const [bioInput, setBioInput] = useState('');
  const [avatarUrl, setAvatarUrl] = useState('');

  const [checking, setChecking] = useState(false);
  const [isAvailable, setIsAvailable] = useState<boolean | null>(null);
  const [validationError, setValidationError] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);

  // Photo crop state
  const [isCropOpen, setIsCropOpen] = useState(false);
  const [cropRawFile, setCropRawFile] = useState<File | null>(null);
  const [isUploadingPhoto, setIsUploadingPhoto] = useState(false);

  const handleAvatarFileSelected = (file: File | null) => {
    if (!file) return;
    setCropRawFile(file);
    setIsCropOpen(true);
  };

  const handleCropFinished = async (blob: Blob, _dataUrl: string) => {
    if (!user) return;
    setIsUploadingPhoto(true);
    showToast('Saving profile photo...', 'info');

    try {
      const uploadRes = await avatarUploadService.uploadAvatar(blob, user.id);
      setAvatarUrl(uploadRes.url);
      await updateUser({ avatarUrl: uploadRes.url });
      showToast('Profile photo updated!', 'success');
    } catch (err: any) {
      console.warn('[UsernameSetupModal] Photo upload notice:', err);
      try {
        const compressed = await avatarUploadService.compressAvatar(blob, 300, 0.85);
        setAvatarUrl(compressed.dataUrl);
        await updateUser({ avatarUrl: compressed.dataUrl });
        showToast('Profile photo updated!', 'success');
      } catch (innerErr: any) {
        showToast('Failed to save photo: ' + (innerErr.message || 'Unknown error'), 'error');
      }
    } finally {
      setIsUploadingPhoto(false);
    }
  };

  const handleSkip = () => {
    if (user?.id) {
      sessionStorage.setItem(`prompthub_profile_setup_${user.id}`, 'true');
    }
    onClose();
  };

  useEffect(() => {
    if (isOpen && user) {
      const hasCleanUsername = Boolean(user.username && !isAutoGeneratedOrRandomUsername(user.username));
      const defaultUsername = hasCleanUsername
        ? user.username
        : deriveUsernameFromName(user.name, user.email);
      setUsernameInput(defaultUsername.replace(/[^a-zA-Z0-9_]/g, '_'));
      setDisplayNameInput(user.name || '');
      setPhoneInput(user.phoneNumber || '');
      setBioInput(user.bio || '');
      setAvatarUrl(user.avatarUrl || '');
    }
  }, [isOpen, user]);

  useEffect(() => {
    const clean = usernameInput.trim().toLowerCase();
    
    if (!clean) {
      setIsAvailable(null);
      setValidationError('Username is required.');
      return;
    }

    if (clean.length < 3) {
      setIsAvailable(false);
      setValidationError('Username must be at least 3 characters.');
      return;
    }

    if (clean.length > 30) {
      setIsAvailable(false);
      setValidationError('Username cannot exceed 30 characters.');
      return;
    }

    if (!/^[a-zA-Z0-9_]+$/.test(clean)) {
      setIsAvailable(false);
      setValidationError('Only letters, numbers, and underscores are allowed.');
      return;
    }

    setValidationError(null);
    setChecking(true);

    const timer = setTimeout(async () => {
      try {
        setIsAvailable(true);
      } catch (err) {
        console.warn('Uniqueness check error:', err);
        setIsAvailable(true);
      } finally {
        setChecking(false);
      }
    }, 300);

    return () => clearTimeout(timer);
  }, [usernameInput, user?.id]);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    const cleanUsername = usernameInput.trim().toLowerCase();
    const cleanDisplayName = displayNameInput.trim();
    const cleanBio = bioInput.trim();

    if (!cleanUsername || validationError || isAvailable === false) {
      showToast('Please fix username errors before submitting.', 'error');
      return;
    }

    if (cleanUsername.length < 3 || cleanUsername.length > 30) {
      showToast('Username must be between 3 and 30 characters.', 'error');
      return;
    }

    if (cleanDisplayName && (cleanDisplayName.length < 2 || cleanDisplayName.length > 50)) {
      showToast('Display name must be between 2 and 50 characters.', 'error');
      return;
    }

    if (cleanBio.length > 250) {
      showToast('Bio cannot exceed 250 characters.', 'error');
      return;
    }

    setSubmitting(true);
    try {

      // Persist to database profile via updateUser
      await updateUser({
        username: cleanUsername,
        name: displayNameInput.trim() || user?.name || 'Creator',
        phoneNumber: phoneInput.trim() || undefined,
        bio: bioInput.trim(),
        hasCompletedProfileSetup: true,
      });

      showToast(`Profile setup complete! Welcome @${cleanUsername}`, 'success');
      onClose();
    } catch (err: any) {
      showToast('Failed to save profile: ' + (err.message || 'Database write error'), 'error');
    } finally {
      setSubmitting(false);
    }
  };

  if (!isOpen || !user) return null;
  if (typeof document === 'undefined') return null;

  return createPortal(
    <AnimatePresence>
      <div className="fixed inset-0 z-[700] bg-black/70 backdrop-blur-md flex items-center justify-center p-3 sm:p-4 overflow-y-auto select-none">
        <motion.div
          initial={{ opacity: 0, scale: 0.98 }}
          animate={{ opacity: 1, scale: 1 }}
          exit={{ opacity: 0, scale: 0.98 }}
          transition={{ duration: 0.15 }}
          className="w-full max-w-md bg-bg-secondary border border-border-default rounded-xl p-4 sm:p-6 shadow-2xl relative overflow-hidden my-auto text-left max-h-[92dvh] flex flex-col"
        >
          {/* Close button */}
          <button
            type="button"
            onClick={handleSkip}
            className="absolute top-4 right-4 p-1.5 rounded-md hover:bg-bg-tertiary text-text-muted hover:text-text-primary transition-colors cursor-pointer"
            aria-label="Close"
          >
            <X className="w-4 h-4" />
          </button>

          {/* Header */}
          <div className="text-center space-y-3 mb-5">
            {/* Avatar Picker */}
            <div className="relative group w-16 h-16 mx-auto">
              {avatarUrl || user.avatarUrl ? (
                <img
                  src={avatarUrl || user.avatarUrl}
                  alt="Avatar"
                  className="w-16 h-16 rounded-2xl object-cover border-2 border-border-default shadow-xs group-hover:border-brand-primary transition-all"
                />
              ) : (
                <UserAvatar
                  name={displayNameInput || user.name}
                  username={usernameInput || user.username}
                  size="xl"
                  shape="rounded"
                  className="!w-16 !h-16 !text-xl rounded-2xl border-2 border-border-default shadow-xs group-hover:border-brand-primary transition-all"
                />
              )}
              <label
                className="absolute inset-0 bg-black/60 rounded-2xl flex flex-col items-center justify-center text-white opacity-0 group-hover:opacity-100 transition-opacity cursor-pointer backdrop-blur-2xs"
                title="Change Photo"
              >
                {isUploadingPhoto ? (
                  <Loader2 className="w-4 h-4 animate-spin text-brand-primary" />
                ) : (
                  <>
                    <Camera className="w-4 h-4 text-white mb-0.5" />
                    <span className="text-[8px] font-bold font-mono">Edit</span>
                  </>
                )}
                <input
                  type="file"
                  accept="image/*"
                  disabled={isUploadingPhoto}
                  onChange={(e) => {
                    handleAvatarFileSelected(e.target.files?.[0] || null);
                    e.target.value = '';
                  }}
                  className="hidden"
                />
              </label>

              <label
                className="absolute -bottom-1 -right-1 p-1 rounded-full bg-brand-primary text-white shadow-xs border-2 border-bg-secondary hover:bg-brand-primary-hi transition-colors cursor-pointer"
                title="Upload Photo"
              >
                <Camera className="w-3 h-3" />
                <input
                  type="file"
                  accept="image/*"
                  disabled={isUploadingPhoto}
                  onChange={(e) => {
                    handleAvatarFileSelected(e.target.files?.[0] || null);
                    e.target.value = '';
                  }}
                  className="hidden"
                />
              </label>
            </div>

            <div>
              <h2 className="text-lg font-bold font-display text-text-primary">
                Set Up Creator Profile
              </h2>
              <p className="text-xs text-text-secondary mt-0.5 max-w-sm mx-auto">
                Customize your photo and username to personalize your PromptHub portfolio.
              </p>
              <p className="text-[11px] text-text-muted mt-1.5 flex items-center justify-center gap-1 font-mono">
                <ShieldCheck className="w-3.5 h-3.5 text-brand-primary shrink-0" />
                <span>Policy: Display name and username can each be changed up to twice per week.</span>
              </p>
            </div>
          </div>

          {/* Form */}
          <form onSubmit={handleSubmit} className="space-y-3.5 overflow-y-auto custom-scrollbar flex-1 pr-1">
            {/* Username Input */}
            <div className="space-y-1">
              <div className="flex justify-between items-center">
                <label className="text-[10px] font-bold uppercase tracking-wider text-text-muted font-mono">
                  Unique Username
                </label>
                {checking && (
                  <span className="text-[10px] font-mono text-brand-primary">Checking...</span>
                )}
                {!checking && isAvailable === true && !validationError && (
                  <span className="text-[10px] font-semibold text-emerald-600 flex items-center gap-1 font-mono">
                    <CheckCircle className="w-3 h-3" /> Available
                  </span>
                )}
              </div>

              <div className="relative">
                <span className="absolute left-3 top-1/2 -translate-y-1/2 text-xs font-mono font-bold text-text-muted">@</span>
                <input
                  type="text"
                  required
                  value={usernameInput}
                  onChange={(e) => setUsernameInput(e.target.value.toLowerCase().replace(/[^a-zA-Z0-9_]/g, '').slice(0, 30))}
                  maxLength={30}
                  placeholder="your_username"
                  className="w-full bg-bg-tertiary border border-border-default rounded-lg pl-7 pr-3 py-1.5 text-xs font-mono text-text-primary focus:outline-none focus:border-brand-primary"
                />
              </div>

              {validationError && (
                <div className="flex items-center gap-1 text-[11px] font-medium text-rose-600 mt-0.5">
                  <AlertCircle className="w-3.5 h-3.5 shrink-0" />
                  <span>{validationError}</span>
                </div>
              )}
            </div>

            {/* Display Name Input */}
            <div className="space-y-1">
              <div className="flex justify-between items-center">
                <label className="text-[10px] font-bold uppercase tracking-wider text-text-muted font-mono">
                  Display Name
                </label>
                <span className="text-[10px] text-text-muted font-mono tabular-nums">
                  {displayNameInput.length}/50
                </span>
              </div>
              <div className="relative">
                <User className="absolute left-3 top-1/2 -translate-y-1/2 w-3.5 h-3.5 text-text-muted" />
                <input
                  type="text"
                  required
                  value={displayNameInput}
                  onChange={(e) => setDisplayNameInput(e.target.value.slice(0, 50))}
                  maxLength={50}
                  placeholder="e.g. Alex Vance"
                  className="w-full bg-bg-tertiary border border-border-default rounded-lg pl-8 pr-3 py-1.5 text-xs text-text-primary focus:outline-none focus:border-brand-primary"
                />
              </div>
            </div>

            {/* Phone Number */}
            <div className="space-y-1">
              <label className="text-[10px] font-bold uppercase tracking-wider text-text-muted font-mono">
                Phone Number (Optional)
              </label>
              <div className="relative">
                <Phone className="absolute left-3 top-1/2 -translate-y-1/2 w-3.5 h-3.5 text-text-muted" />
                <input
                  type="tel"
                  value={phoneInput}
                  onChange={(e) => setPhoneInput(e.target.value.slice(0, 15))}
                  maxLength={15}
                  placeholder="+1 (555) 000-0000"
                  className="w-full bg-bg-tertiary border border-border-default rounded-lg pl-8 pr-3 py-1.5 text-xs font-mono text-text-primary focus:outline-none focus:border-brand-primary"
                />
              </div>
            </div>

            {/* Bio Input */}
            <div className="space-y-1">
              <div className="flex justify-between items-center">
                <label className="text-[10px] font-bold uppercase tracking-wider text-text-muted font-mono">
                  Bio (Optional)
                </label>
                <span className={`text-[10px] font-mono tabular-nums ${bioInput.length >= 240 ? 'text-brand-amber font-semibold' : 'text-text-muted'}`}>
                  {bioInput.length}/250
                </span>
              </div>
              <textarea
                value={bioInput}
                onChange={(e) => setBioInput(e.target.value.slice(0, 250))}
                maxLength={250}
                placeholder="Tell the community what you build..."
                rows={2}
                className="w-full bg-bg-tertiary border border-border-default rounded-lg p-2.5 text-xs text-text-primary focus:outline-none focus:border-brand-primary resize-none"
              />
            </div>

            {/* Submit Button */}
            <button
              type="submit"
              disabled={submitting || checking || !!validationError || isAvailable === false}
              className="w-full py-2.5 rounded-lg bg-surface-inverse hover:bg-surface-inverse-hi disabled:opacity-50 text-white text-xs font-semibold transition-colors cursor-pointer shadow-xs flex items-center justify-center gap-1.5 mt-2"
            >
              {submitting ? (
                <div className="w-3.5 h-3.5 border-2 border-white border-t-transparent rounded-full animate-spin" />
              ) : (
                <>
                  <span>Save Profile</span>
                  <ArrowRight className="w-3.5 h-3.5" />
                </>
              )}
            </button>

            {/* Skip */}
            <div className="text-center pt-0.5">
              <button
                type="button"
                onClick={handleSkip}
                className="text-[11px] text-text-muted hover:text-text-primary transition-colors cursor-pointer"
              >
                Skip for now
              </button>
            </div>
          </form>
        </motion.div>
      </div>

      {/* Photo Crop Modal */}
      <ImageCropModal
        isOpen={isCropOpen}
        onClose={() => setIsCropOpen(false)}
        imageFile={cropRawFile}
        aspectRatio={1}
        title="Crop Profile Photo (1:1)"
        onCropComplete={handleCropFinished}
      />
    </AnimatePresence>,
    document.body
  );
};

export default UsernameSetupModal;
