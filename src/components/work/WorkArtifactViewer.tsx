import React, { useState } from 'react';
import { 
  FileText, 
  Copy, 
  Check, 
  Download, 
  Code, 
  Eye, 
  Award,
  Calendar,
  Layers,
  HardDrive,
  Loader2
} from 'lucide-react';
import type { WorkArtifact } from '../../types/work';
import { workService } from '../../services/work/workService';

interface WorkArtifactViewerProps {
  artifacts: WorkArtifact[];
  selectedArtifactId?: string;
  onSelectArtifact?: (id: string) => void;
}

export const WorkArtifactViewer: React.FC<WorkArtifactViewerProps> = ({
  artifacts,
  selectedArtifactId,
  onSelectArtifact,
}) => {
  const [viewMode, setViewMode] = useState<'preview' | 'raw'>('preview');
  const [isCopied, setIsCopied] = useState(false);
  const [isSavingToDrive, setIsSavingToDrive] = useState(false);
  const [isDriveSaved, setIsDriveSaved] = useState(false);

  const activeArtifact = artifacts.find((a) => a.id === selectedArtifactId) || artifacts[0];

  const handleCopy = async () => {
    if (!activeArtifact) return;
    await navigator.clipboard.writeText(activeArtifact.content);
    setIsCopied(true);
    setTimeout(() => setIsCopied(false), 1500);
  };

  const handleDownload = () => {
    if (!activeArtifact) return;
    const blob = new Blob([activeArtifact.content], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${activeArtifact.name || 'artifact'}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleSaveToDrive = async () => {
    if (!activeArtifact || isSavingToDrive) return;
    setIsSavingToDrive(true);
    try {
      const res = await workService.saveArtifactToDrive(activeArtifact.id);
      if (res.success) {
        setIsDriveSaved(true);
        setTimeout(() => setIsDriveSaved(false), 2500);
      }
    } finally {
      setIsSavingToDrive(false);
    }
  };

  if (!activeArtifact || artifacts.length === 0) {
    return (
      <div className="bg-bg-secondary border border-border-default rounded-xl flex flex-col items-center justify-center p-8 text-center h-full">
        <Award className="w-10 h-10 text-text-muted/60 mb-2" />
        <h3 className="text-sm font-semibold text-text-primary">No Artifacts Produced</h3>
        <p className="text-xs text-text-muted mt-1 max-w-sm">
          Deliverables, implementation reports, and test results generated by agents will appear here.
        </p>
      </div>
    );
  }

  return (
    <div className="bg-bg-secondary border border-border-default rounded-xl flex flex-col h-full overflow-hidden shadow-2xs">
      {/* Header Bar */}
      <div className="bg-bg-tertiary/60 border-b border-border-subtle px-3 py-2 flex items-center justify-between gap-3 shrink-0 flex-wrap">
        <div className="flex items-center gap-2 min-w-0">
          <FileText className="w-4 h-4 text-brand-primary shrink-0" />

          {/* Artifact selector if multiple */}
          {artifacts.length > 1 ? (
            <select
              value={activeArtifact.id}
              onChange={(e) => onSelectArtifact?.(e.target.value)}
              aria-label="Select Artifact"
              className="bg-bg-secondary border border-border-default rounded px-2 py-1 text-xs font-mono text-text-primary focus:outline-none cursor-pointer min-h-[44px] sm:min-h-[28px]"
            >
              {artifacts.map((a) => (
                <option key={a.id} value={a.id}>
                  {a.title} ({a.type})
                </option>
              ))}
            </select>
          ) : (
            <span className="text-xs font-semibold text-text-primary truncate">
              {activeArtifact.title}
            </span>
          )}

          <span className="text-[10px] font-mono px-1.5 py-0.5 rounded bg-bg-secondary border border-border-default text-text-muted uppercase">
            {activeArtifact.type}
          </span>
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-1.5">
          <div className="flex items-center bg-bg-secondary rounded-md p-0.5 border border-border-default">
            <button
              type="button"
              onClick={() => setViewMode('preview')}
              title="Preview Mode"
              className={`min-h-[44px] min-w-[44px] sm:min-h-[26px] sm:min-w-[26px] flex items-center justify-center rounded transition-colors ${
                viewMode === 'preview' ? 'bg-bg-tertiary text-text-primary font-medium' : 'text-text-muted hover:text-text-primary'
              }`}
            >
              <Eye className="w-3.5 h-3.5" />
            </button>
            <button
              type="button"
              onClick={() => setViewMode('raw')}
              title="Raw Markdown Mode"
              className={`min-h-[44px] min-w-[44px] sm:min-h-[26px] sm:min-w-[26px] flex items-center justify-center rounded transition-colors ${
                viewMode === 'raw' ? 'bg-bg-tertiary text-text-primary font-medium' : 'text-text-muted hover:text-text-primary'
              }`}
            >
              <Code className="w-3.5 h-3.5" />
            </button>
          </div>

          <button
            type="button"
            onClick={handleCopy}
            title="Copy Content"
            className="min-h-[44px] min-w-[44px] sm:min-h-[28px] sm:min-w-[28px] flex items-center justify-center rounded-md border border-border-default bg-bg-secondary hover:bg-bg-tertiary text-text-secondary hover:text-text-primary transition-colors cursor-pointer"
          >
            {isCopied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
          </button>

          <button
            type="button"
            onClick={handleDownload}
            title="Download Artifact"
            className="min-h-[44px] min-w-[44px] sm:min-h-[28px] sm:min-w-[28px] flex items-center justify-center rounded-md border border-border-default bg-bg-secondary hover:bg-bg-tertiary text-text-secondary hover:text-text-primary transition-colors cursor-pointer"
          >
            <Download className="w-3.5 h-3.5" />
          </button>

          <button
            type="button"
            onClick={handleSaveToDrive}
            disabled={isSavingToDrive}
            title={isDriveSaved ? 'Saved to Google Drive' : 'Save to Google Drive Vault'}
            className={`min-h-[44px] sm:min-h-[28px] px-2.5 flex items-center gap-1.5 rounded-md border text-xs font-mono transition-colors cursor-pointer disabled:opacity-50 ${
              isDriveSaved
                ? 'border-emerald-500 bg-emerald-50 text-emerald-700 dark:bg-emerald-950/60 dark:text-emerald-300'
                : 'border-border-default bg-bg-secondary hover:bg-bg-tertiary text-text-secondary hover:text-text-primary'
            }`}
          >
            {isSavingToDrive ? (
              <Loader2 className="w-3.5 h-3.5 animate-spin text-brand-primary" />
            ) : isDriveSaved ? (
              <Check className="w-3.5 h-3.5 text-emerald-600" />
            ) : (
              <HardDrive className="w-3.5 h-3.5 text-sky-600" />
            )}
            <span className="hidden sm:inline">{isDriveSaved ? 'Saved to Drive' : 'Save to Drive'}</span>
          </button>
        </div>
      </div>

      {/* Artifact Content Body */}
      <div className="flex-1 overflow-auto p-4 sm:p-6 bg-bg-primary selection:bg-brand-primary selection:text-white">
        {viewMode === 'raw' ? (
          <pre className="font-mono text-xs text-text-primary whitespace-pre-wrap leading-relaxed">
            {activeArtifact.content}
          </pre>
        ) : (
          <div className="prose prose-sm max-w-none text-text-primary space-y-3 font-sans leading-relaxed">
            {/* Simple Markdown Rendering */}
            {activeArtifact.content.split('\n\n').map((block, idx) => {
              const trimmed = block.trim();
              if (trimmed.startsWith('# ')) {
                return (
                  <h1 key={idx} className="text-xl font-bold text-text-primary tracking-tight pb-2 border-b border-border-subtle">
                    {trimmed.replace(/^# /, '')}
                  </h1>
                );
              }
              if (trimmed.startsWith('## ')) {
                return (
                  <h2 key={idx} className="text-base font-semibold text-text-primary pt-2">
                    {trimmed.replace(/^## /, '')}
                  </h2>
                );
              }
              if (trimmed.startsWith('### ')) {
                return (
                  <h3 key={idx} className="text-sm font-semibold text-text-primary">
                    {trimmed.replace(/^### /, '')}
                  </h3>
                );
              }
              if (trimmed.startsWith('- ') || trimmed.startsWith('* ')) {
                const items = trimmed.split('\n').map((l) => l.replace(/^[-*]\s+/, ''));
                return (
                  <ul key={idx} className="list-disc pl-5 text-xs text-text-secondary space-y-1">
                    {items.map((item, iIdx) => (
                      <li key={iIdx}>{item}</li>
                    ))}
                  </ul>
                );
              }
              if (trimmed.startsWith('```')) {
                const codeContent = trimmed.replace(/^```[a-z]*\n/, '').replace(/\n```$/, '');
                return (
                  <pre key={idx} className="p-3 rounded-lg bg-[#0D1110] text-stone-200 font-mono text-[11px] overflow-x-auto">
                    {codeContent}
                  </pre>
                );
              }

              const imgMatch = trimmed.match(/^!\[([^\]]*)\]\((https?:\/\/[^)]+)\)/);
              if (imgMatch) {
                const alt = imgMatch[1] || 'Generated image';
                const src = imgMatch[2];
                return (
                  <div key={idx} className="rounded-xl overflow-hidden border border-border-default bg-black/10 my-3 max-w-xl">
                    <img src={src} alt={alt} className="w-full max-h-96 object-contain bg-black/5" loading="lazy" />
                    <div className="p-2 bg-bg-secondary border-t border-border-subtle flex items-center justify-between text-xs">
                      <span className="font-semibold text-text-primary truncate">{alt}</span>
                      <a href={src} target="_blank" rel="noopener noreferrer" className="text-brand-primary hover:underline text-[11px] shrink-0 font-mono">
                        Open Full Image ↗
                      </a>
                    </div>
                  </div>
                );
              }

              return (
                <p key={idx} className="text-xs text-text-secondary leading-relaxed">
                  {trimmed}
                </p>
              );
            })}
          </div>
        )}
      </div>

      {/* Meta Footer */}
      <div className="px-3 py-1.5 bg-bg-secondary border-t border-border-subtle flex items-center justify-between text-[11px] font-mono text-text-muted shrink-0">
        <div className="flex items-center gap-3">
          <span className="flex items-center gap-1">
            <Calendar className="w-3 h-3 text-text-muted" />
            <span>{new Date(activeArtifact.createdAt).toLocaleTimeString()}</span>
          </span>
          <span className="flex items-center gap-1">
            <Layers className="w-3 h-3 text-text-muted" />
            <span>v{activeArtifact.version}</span>
          </span>
        </div>
        <span>{activeArtifact.size} bytes</span>
      </div>
    </div>
  );
};
