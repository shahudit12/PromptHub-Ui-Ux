/**
 * Resolves the catalog entry for a model identifier.
 *
 * Extracted so that cost resolution and membership testing can never drift apart:
 * `getModelCreditCost` and `isKnownCatalogModel` must agree on what "known" means,
 * because the router uses the latter to decide whether a model may be billed at all.
 */
function lookupCatalogEntry(modelId?: string | null): ModelCostMetadata | undefined {
  if (!modelId) return undefined;
  const canonical = getCanonicalModel(modelId);
  if (canonical) {
    let tier: ModelTier = 'standard';
    if (canonical.freeOrPaid === 'FREE') tier = 'economy';
    else if (canonical.capabilities?.reasoning) tier = 'reasoning';
    else if (canonical.pricing.promptHubCreditCost >= 2) tier = 'frontier';
    else tier = 'economy';

    return {
      id: canonical.canonicalModelId,
      name: canonical.displayName,
      provider: canonical.modelOwner,
      tier,
      creditCost: canonical.pricing.promptHubCreditCost,
      inputCostPer1MTokensUsd: canonical.pricing.promptUsdPerMillion,
      outputCostPer1MTokensUsd: canonical.pricing.completionUsdPerMillion,
      maxOutputTokens: canonical.maxOutput,
      supportsReasoning: canonical.capabilities?.reasoning,
      description: canonical.displayName,
    };
  }

  const clean = modelId.toLowerCase().trim();
  const normalized = clean.replace(/^(openrouter\/|openai\/|anthropic\/|google\/)/, '');
  return MODEL_COST_CATALOG[clean] || MODEL_COST_CATALOG[normalized] || MODEL_COST_CATALOG[modelId];
}

/**
 * Whether this model identifier corresponds to a real, priced catalog entry.
 *
 * Callers must use this before routing a model to a PAID provider. `getModelCreditCost`
 * deliberately returns a conservative non-zero fallback for unrecognised IDs, which is
 * the correct behaviour for pricing a known-but-unlisted model but must never be used
 * to justify EXECUTING an unrecognised one: that would bill a user for a model the
 * platform cannot vouch for.
 */
export function isKnownCatalogModel(modelId?: string | null): boolean {
  return Boolean(lookupCatalogEntry(modelId));
}

/**
 * Resolves credit deduction for a given model identifier.
 * If model is unknown, returns safe conservative fallback (never 0 or 1).
 */
export function getModelCreditCost(modelId?: string | null): number {
  if (!modelId) return UNKNOWN_MODEL_FALLBACK_CREDIT_COST;
  const found = lookupCatalogEntry(modelId);
  if (found) {
    return found.creditCost;
  }
  return UNKNOWN_MODEL_FALLBACK_CREDIT_COST;
}
